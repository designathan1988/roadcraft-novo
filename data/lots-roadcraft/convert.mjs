// Converts the 38 Roadcraft 4.0 lot projects (lots/*.json, units of 0.4 m) into the engine's design catalog: a
// compact table written between the CATALOG markers of src/world/design.ts. Run: node data/lots-roadcraft/convert.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const designPath = path.resolve(here, '../../src/world/design.ts');
const U = 0.4; // metres per project unit
const FIN = { plaster: 1, ceramic: 2, brick: 3, stone: 4, concrete: 5, wood: 6, metal: 7, glass: 8, tile: 9, roofing: 10, stucco: 11, panel: 12, slate: 13 };
const FILL = { window: 0, wideWindow: 1, ribbon: 2, shopfront: 3, wall: 4, balcony: 5 };
const OPEN = { paving: 1, asphalt: 2, grass: 3 };
const ELEM = { tree: 1, planter: 2, bench: 3, lamp: 4, shrub: 5, flowers: 6, wall: 7, fence: 8, gate: 9, parking: 10 };
const r1 = (v) => Math.round(v * 100) / 100;
const mat = (m, def) => (m ? [FIN[m.finish] ?? def[0], m.colour] : def);

const rows = [];
for (const file of fs.readdirSync(here).filter((f) => f.endsWith('.json')).sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(here, file), 'utf8'));
  const b = j.body;
  const wall = mat(b.materials?.wall, [1, 0xe6d8bd]), trim = mat(b.materials?.trim, [1, 0xf4eee2]), roof = mat(b.materials?.roof, [10, 0x74716a]);
  // lot frame: x centred on the volumes, z from the front (project y = 0) to the back
  const solid = b.volumes.filter((v) => !v.open);
  let x0 = Infinity, x1 = -Infinity, y1 = 0;
  for (const v of b.volumes) { x0 = Math.min(x0, v.x); x1 = Math.max(x1, v.x + v.w); y1 = Math.max(y1, v.y + v.d); }
  const cx = (x0 + x1) / 2;
  const vols = [];
  for (const v of b.volumes) {
    const box = [r1((v.x - cx) * U), r1(v.y * U), r1(v.w * U), r1(v.d * U)];
    if (v.open) { vols.push([...box, 0, 0, 0, 0, OPEN[v.open] ?? 1, 0]); continue; }
    const fills = v.storeys.map((s) => s.facade.fill);
    const ground = FILL[fills[0]] ?? 0;
    const count = {};
    for (const f of fills.slice(1)) count[f] = (count[f] ?? 0) + 1;
    const upper = FILL[Object.entries(count).sort((a, b) => b[1] - a[1])[0]?.[0] ?? fills[0]] ?? 0;
    const balcony = fills.includes('balcony') || v.storeys.some((s) => Object.values(s.facade.bays ?? {}).includes('balcony')) ? 1 : 0;
    const door = v.storeys[0] && Object.values(v.storeys[0].facade.bays ?? {}).some((k) => /door/i.test(k)) ? 1 : 0;
    const vm = mat(v.materials?.wall, wall);
    const row = [...box, v.base, v.storeys.length, v.roof === 'terrace' ? 1 : 0, upper | (ground << 3) | (balcony << 6) | (door << 7), vm[0], vm[1]];
    if (v.outline) row.push(v.outline.flatMap((p) => [r1(p.x), r1(p.y)]));
    vols.push(row);
  }
  const elems = (b.elements ?? []).filter((e) => ELEM[e.kind]).map((e) => [ELEM[e.kind], r1((e.x - cx) * U), r1(e.y * U), r1((e.w ?? 1) * U), r1((e.d ?? 1) * U), r1((e.h ?? 1) * U), Math.round((e.facing ?? 0) * 100) / 100]);
  const name = file.replace(/\.json$/, '');
  rows.push(`  { name: '${name}', fn: '${b.function}', use: '${j.use}', w: ${r1((x1 - x0) * U)}, d: ${r1(y1 * U)}, gh: ${r1(b.groundHeight * U)}, sh: ${r1(b.storeyHeight * U)},\n    wall: [${wall[0]}, 0x${wall[1].toString(16)}], trim: [${trim[0]}, 0x${trim[1].toString(16)}], roof: [${roof[0]}, 0x${roof[1].toString(16)}],\n    vols: ${JSON.stringify(vols)},\n    elems: ${JSON.stringify(elems)} },`);
  void solid;
}
const block = `// CATALOG:BEGIN (generated by data/lots-roadcraft/convert.mjs from the 38 Roadcraft 4.0 projects; do not edit by hand)\nexport const CATALOG: CatalogEntry[] = [\n${rows.join('\n')}\n];\n// CATALOG:END`;
const src = fs.readFileSync(designPath, 'utf8').split('\r\n').join('\n');
const a = src.indexOf('// CATALOG:BEGIN'), e = src.indexOf('// CATALOG:END');
const out = a >= 0 ? src.slice(0, a) + block + src.slice(e + '// CATALOG:END'.length) : src.trimEnd() + '\n\n' + block + '\n';
fs.writeFileSync(designPath, out.split('\n').join('\r\n'));
console.log(`${rows.length} projetos → ${designPath}`);
